#!/usr/bin/env node
// Generate src/keybindings/registry.ts from evidence/keybindings/keybindings.json.
// Usage: node tools/keybindings_gen.mjs [--check]
//   --check  exit 1 when the committed file differs from what would be generated.
import { readFileSync, writeFileSync } from "node:fs";

const evidence = JSON.parse(readFileSync("evidence/keybindings/keybindings.json", "utf8"));
const target = "src/keybindings/registry.ts";

const shortcut = ({ key, modifiers }) => {
  const mods = modifiers ? `, ${JSON.stringify(modifiers)}` : "";
  return key.kind === "logical"
    ? `logical(${JSON.stringify(key.value)}${mods})`
    : `physical(${JSON.stringify(key.code)}, ${JSON.stringify(key.display)}${mods})`;
};

const command = (c) => {
  const key = /^chat\.selectLoadout[1-5]$/.test(c.id) ? { ...c.key, modifiers: ["meta"] } : c.key;
  const fields = [`id: ${JSON.stringify(c.id)}`, `key: ${shortcut(key)}`];
  if (c.additionalKeys) fields.push(`additionalKeys: [${c.additionalKeys.map(shortcut).join(", ")}]`);
  for (const k of ["title", "category", "configurable", "hidden", "displayScope", "description", "when"]) {
    if (c[k] !== undefined) fields.push(`${k}: ${JSON.stringify(c[k])}`);
  }
  return `  { ${fields.join(", ")} },`;
};

const presets = Object.entries(evidence.sendKeyPresets).map(
  ([mode, byId]) =>
    `  ${JSON.stringify(mode)}: {\n${Object.entries(byId)
      .map(([id, list]) => `    ${JSON.stringify(id)}: [${list.map(shortcut).join(", ")}],`)
      .join("\n")}\n  },`,
);

const out = `// Generated by tools/keybindings_gen.mjs from evidence/keybindings/keybindings.json.
// Do not edit by hand. Titles are untrusted third-party strings kept to match behaviour.
import { logical, physical, type Command, type Shortcut } from "./types.ts";

export const STORAGE_KEY = ${JSON.stringify(evidence.storageKey)};

export type SendKeyMode = ${Object.keys(evidence.sendKeyPresets).map((m) => JSON.stringify(m)).join(" | ")};

/** Defaults for the four send-key commands under each legacy \`message_send_key\` mode. */
export const SEND_KEY_PRESETS: Record<SendKeyMode, Record<string, readonly Shortcut[]>> = {
${presets.join("\n")}
};

/** Commands that conflict only with commands in the same group. */
export const CONFLICT_BASE: readonly string[] = ${JSON.stringify(evidence.conflictScopes.base)};
export const CONFLICT_GROUPS: readonly (readonly string[])[] = [
${evidence.conflictScopes.groups.map((g) => `  ${JSON.stringify(g)},`).join("\n")}
];

/** Old override ids mapped to the command that replaced them. */
export const LEGACY_ALIASES: Readonly<Record<string, string>> = ${JSON.stringify(evidence.legacyAliases)};

export const COMMANDS: readonly Command[] = [
${evidence.commands.map(command).join("\n")}
];
`;

if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== out) {
    console.error(`${target} is stale: run node tools/keybindings_gen.mjs`);
    process.exit(1);
  }
} else {
  writeFileSync(target, out);
  console.log(`${evidence.commands.length} commands -> ${target}`);
}
