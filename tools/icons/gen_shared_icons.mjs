// Generates src/components/conductorIcons.generated.ts: the shared icon set
// every screen draws its icons from. Conductor draws Lucide icons (24x24,
// stroke 2): tools/icons/shared-icon-names.txt lists the names, and the shapes
// come from lucide-static@0.577.0 (ISC), the release that matches Conductor's
// chat icons (see tools/icons/README.md).
//
// Usage: npm pack lucide-static@0.577.0 && tar xzf lucide-static-0.577.0.tgz
//        node tools/icons/gen_shared_icons.mjs ./package
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const pkg = process.argv[2];
if (!pkg) throw new Error("usage: gen_shared_icons.mjs <lucide-static package dir>");
const version = JSON.parse(fs.readFileSync(path.join(pkg, "package.json"), "utf8")).version;
if (version !== "0.577.0") throw new Error(`expected lucide-static 0.577.0, got ${version}`);
const nodes = JSON.parse(fs.readFileSync(path.join(pkg, "icon-nodes.json"), "utf8"));
const names = fs.readFileSync(path.join(here, "shared-icon-names.txt"), "utf8").split(/\s+/).filter(Boolean);
const missing = names.filter((n) => !nodes[n]);
if (missing.length) throw new Error(`missing in lucide-static: ${missing.join(", ")}`);

const lines = names.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(nodes[n].map(([tag, attrs]) => [tag, attrs]))},`);
const out = `// Generated by tools/icons/gen_shared_icons.mjs from lucide-static@${version}. Do not edit.
// Lucide icons, ISC License, Copyright (c) Lucide Icons and Contributors.
export type IconNode = [tag: string, attrs: Record<string, string>][];

export const CONDUCTOR_ICONS = {
${lines.join("\n")}
} as const satisfies Record<string, IconNode>;

export type ConductorIconName = keyof typeof CONDUCTOR_ICONS;
`;
const dest = path.resolve(here, "../../src/components/conductorIcons.generated.ts");
fs.writeFileSync(dest, out);
console.log(`wrote ${names.length} icons to ${path.relative(process.cwd(), dest)}`);
