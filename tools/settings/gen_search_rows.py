"""Settings search rows, from Conductor's row registry, kept to the rows OpenConductor renders.

Conductor's "Search settings" (`a9a`, renderApp-D_fmY7hW.js @11,250,104) searches its pages
(`yUi`) and every registered row (`xUi`): a row's title, description, tab and search terms. The
rows come from evidence/settings/settings-search-rows.json (tools/settings/extract_settings_rows.py
over Conductor 0.87.6's decoded frontend), filtered as `xUi` does for a local user: no
excludeFromSearch rows, no "-panel" ids, no agent "harness" rows (`xGt`, the agent tabs stand in
for them), no internal-only rows, and only tabs a local user reaches (`Uba`). A row is
kept only when its title (brand-normalised to OpenConductor) is a string literal or JSX text in src/settings, so a
search never offers a row that this app does not have.

    python3 tools/settings/gen_search_rows.py   # writes src/settings/searchRows.generated.ts

Strings are Conductor's copy, untrusted data, used only as search text.
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
REGISTRY = ROOT / "evidence/settings/settings-search-rows.json"
OUT = ROOT / "src/settings/searchRows.generated.ts"

# Tabs a local user can reach (Conductor's `Uba` gates: ports needs a cloud organization,
# internal an internal build, organization pages an organization).
USER_TABS = {"general", "account", "appearance", "models", "git", "providers", "environment", "experimental", "advanced", "terminal"}
REPO_TABS = {"scripts", "actions", "misc"}
# Conductor's `xGt`: rows that open an agent tab instead (the tab is listed as its own result).
HARNESS_ROWS = {"providers:claude", "providers:codex", "providers:cursor"}


def brand(s: str) -> str:
    return re.sub(r"\bConductor\b", "OpenConductor", s)


def source_text() -> str:
    parts = []
    for p in sorted((ROOT / "src/settings").rglob("*.ts*")):
        if p.name.endswith(".test.ts") or p.name == OUT.name:
            continue
        parts.append(p.read_text())
    return "\n".join(parts)


def rendered(text: str, src: str) -> bool:
    """The text as a string literal or JSX text, not just inside a comment."""
    return any(f"{a}{text}{b}" in src for a, b in (('"', '"'), ("'", "'"), ("`", "`"), (">", "<"), ("> ", " <")))


def main() -> None:
    rows = json.loads(REGISTRY.read_text())["rows"]
    src = source_text()
    out = []
    seen = set()
    for r in rows:
        tab = r["tab"]
        if tab not in USER_TABS and tab not in REPO_TABS:
            continue
        rid = r.get("id") or ""
        if r["excludeFromSearch"] or r["internalOnly"] or rid.endswith("-panel") or rid in HARNESS_ROWS:
            continue
        title = brand(r["title"])
        # Conductor's `xUi` labels the default-model row "Edit models".
        label = "Edit models" if r.get("key") == "default_model" else title
        if not rendered(title, src) and not rendered(label, src):
            continue
        scope = "user" if "user" in (r["scopes"] or ["user"]) else "repo"
        if tab in REPO_TABS:
            scope = "repo"
        key = (tab, label)
        if key in seen:
            continue
        seen.add(key)
        desc = r["description"]
        out.append({"tab": tab, "scope": scope, "label": label, "description": brand(desc) if desc else None, "searchTerms": r["searchTerms"]})
    lines = [
        "// Generated by tools/settings/gen_search_rows.py from evidence/settings/settings-search-rows.json; do not edit.",
        "// Conductor's searchable settings rows that OpenConductor renders (title found in src/settings).",
        "",
        "export interface SearchRow {",
        "  tab: string;",
        '  scope: "user" | "repo";',
        "  label: string;",
        "  description: string | null;",
        "  /** Conductor's `searchTerms`, matched with the keywords. */",
        "  searchTerms: string[];",
        "}",
        "",
        "export const SEARCH_ROWS: readonly SearchRow[] = [",
    ]
    for o in out:
        lines.append(f"  {json.dumps(o, ensure_ascii=False)},")
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{len(out)} rows -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
