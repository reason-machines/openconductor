#!/usr/bin/env python3
"""Generates src/features/chat/toolIconData.ts: the icon geometry Conductor's
chat uses for tool rows, summary rows, the turn footer and file badges.

Input: an esbuild-pretty-printed copy of Conductor v0.87.6's decoded
renderApp-D_fmY7hW.js (see evidence/chat/README.md for how it is decoded).
The icons are lucide (ISC) and simple-icons / Font Awesome file glyphs that
Conductor bundles; only path data is read. The file is data, never executed.

  python3 tools/chat/gen_tool_icons.py <renderApp.pretty.js> > src/features/chat/toolIconData.ts
"""
import json
import re
import sys

src = open(sys.argv[1]).read()

LUCIDE = ["terminal", "file-text", "search", "file-search", "file-pen", "square-check-big", "globe", "file-code",
          "bot", "brain", "chevron-down", "chevron-right", "plus", "minus", "circle-check", "ellipsis", "circle-x",
          "copy", "check", "wrench", "clock", "circle", "message-square-more", "file-diff", "message-square",
          "messages-square", "laptop", "image", "clipboard-list", "biceps-flexed", "slash", "users", "send", "radio",
          "circle-alert", "trash-2", "message-circle"]
FILES = ["typescript", "react", "javascript", "json", "markdown", "css", "python", "rust", "html", "yaml", "bash",
         "go", "settings", "file-text", "file-image", "file-code", "file"]


def attrs(s):
    return {k: v for k, v in re.findall(r'(\w+): "([^"]*)"', s) if k != "key"}


lucide = {}
for name in LUCIDE:
    m = re.search(r'(\w+) = (\[\[[^;]*?\]\]), \w+ = Ln\("%s", \1\)' % re.escape(name), src)
    if not m:
        sys.exit(f"lucide icon not found: {name}")
    lucide[name] = [[t, attrs(a)] for t, a in re.findall(r'\["(\w+)", \{([^}]*)\}\]', m.group(2))]

table = dict(re.findall(r'"?([\w-]+)"?: (\w+)', re.search(r"const K_s = \{(.*?)\}, Y_s", src).group(1)))
files = {}
for name in FILES:
    fn = table[name]
    m = re.search(r"function %s\(t4\) \{\n  return uo\((\{.*?\})\)\(t4\);" % re.escape(fn), src, re.S)
    if not m:
        sys.exit(f"file icon not found: {name}")
    body = m.group(1)
    files[name] = {
        "viewBox": re.search(r'viewBox: "([^"]*)"', body).group(1),
        "nodes": [[t, attrs(a)] for t, a in re.findall(r'tag: "(\w+)", attr: \{([^}]*)\}', body)],
    }

print("// Generated by tools/chat/gen_tool_icons.py from Conductor v0.87.6's renderApp chunk: do not edit.")
print("// Lucide icons (ISC) as Conductor draws them in chat (24x24, stroke 2), and the filled")
print("// file-type glyphs its file badges use. Path data only.")
print("export type IconNode = [tag: string, attrs: Record<string, string>];")
print(f"export const LUCIDE = {json.dumps(lucide, indent=1)} as const satisfies Record<string, readonly IconNode[]>;")
print(f"export const FILE_GLYPHS = {json.dumps(files, indent=1)} as const satisfies Record<string, {{ viewBox: string; nodes: readonly IconNode[] }}>;")
