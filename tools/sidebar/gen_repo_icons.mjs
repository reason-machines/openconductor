// Generates src/components/repoIcons.generated.ts: the repository icon set the
// sidebar's "Change repository icon" picker offers. The names are the 238
// `repo-icons/*.svg` assets of Conductor v0.87.6 (REA: decoded
// renderApp-D_fmY7hW.js, import map before `J$t`), listed in
// repo-icon-names.txt; the shapes come from lucide-static@0.577.0 (ISC), the
// first release that has all 238.
//
// Usage: npm pack lucide-static@0.577.0 && tar xzf lucide-static-0.577.0.tgz
//        node tools/sidebar/gen_repo_icons.mjs ./package
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const pkg = process.argv[2];
if (!pkg) throw new Error("usage: gen_repo_icons.mjs <lucide-static package dir>");
const version = JSON.parse(fs.readFileSync(path.join(pkg, "package.json"), "utf8")).version;
if (version !== "0.577.0") throw new Error(`expected lucide-static 0.577.0, got ${version}`);
const nodes = JSON.parse(fs.readFileSync(path.join(pkg, "icon-nodes.json"), "utf8"));
const names = fs.readFileSync(path.join(here, "repo-icon-names.txt"), "utf8").split(/\s+/).filter(Boolean);
const missing = names.filter((n) => !nodes[n]);
if (missing.length) throw new Error(`missing in lucide-static: ${missing.join(", ")}`);

const lines = names.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(nodes[n].map(([tag, attrs]) => [tag, attrs]))},`);
const out = `// Generated by tools/sidebar/gen_repo_icons.mjs from lucide-static@${version}. Do not edit.
// Lucide icons, ISC License, Copyright (c) Lucide Icons and Contributors.
export type IconNode = [tag: string, attrs: Record<string, string>][];

export const REPO_ICONS: Record<string, IconNode> = {
${lines.join("\n")}
};
`;
const dest = path.resolve(here, "../../src/components/repoIcons.generated.ts");
fs.writeFileSync(dest, out);
console.log(`wrote ${names.length} icons to ${path.relative(process.cwd(), dest)}`);
