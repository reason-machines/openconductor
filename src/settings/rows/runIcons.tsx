export const RUN_ICON_NAMES = Object.keys(ICONS);

/** Conductor's `D9i`: "flask-conical" → "Flask Conical". */
export function iconLabel(name: string): string {
  return name
    .split("-")
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(" ");
}

export function RunIcon({ name, size = 16 }: { name: string; size?: number }) {
  const known = name in ICONS ? name : "play";
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill={known === "play" ? "currentColor" : "none"}
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden
    >
      {ICONS[known]}
    </svg>
  );
}
