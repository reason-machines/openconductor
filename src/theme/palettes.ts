// The one place colour values live. Every component reads semantic CSS
// variables (`var(--background)`, `var(--muted-foreground)`, ...); this module
// turns the palette chosen in Settings > Appearance into a stylesheet and
// installs it, so switching palettes is a stylesheet swap with no reload.
//
// Stone is Conductor's warm palette, verbatim from evidence/frontend/css-tokens.json
// (`:root,.light`, `.dark` and `html.dark.low-contrast-dark`). Neutral is the
// default: pure greys with a black or white accent and no hue. Blue, Slate and
// Zinc are cool neutrals with their own accent. Each defines light and dark
// values for every base token below; low-contrast dark overrides a subset.
//
// Derived tokens (hover, active, sidebar muted text, ...) are computed in
// tokens.css with color-mix from these base tokens, so they follow the palette.
// FIXED_TOKENS hold colours that carry meaning and stay the same in every
// palette: status dots, file-type tints, syntax colours, collaborator colours.

export const PALETTE_IDS = ["neutral", "stone", "blue", "slate", "zinc"] as const;
export type PaletteId = (typeof PALETTE_IDS)[number];
export const DEFAULT_PALETTE: PaletteId = "neutral";

