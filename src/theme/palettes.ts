/** Whether `value` names a palette Settings can store. */
export const isPaletteId = (value: unknown): value is PaletteId =>
  typeof value === "string" && (PALETTE_IDS as readonly string[]).includes(value);

/** The palette to use for a stored value; unknown or missing values fall back to Neutral. */
export const paletteFrom = (value: unknown): PaletteId => (isPaletteId(value) ? value : DEFAULT_PALETTE);

const decl = (name: string, value: string): string => `  --${name}: ${value};`;

/** The declarations of one token set: base tokens, then fixed tokens for the mode. */
const block = (values: Partial<Record<string, string>>): string =>
  Object.entries(values)
    .map(([name, value]) => decl(name, value as string))
    .join("\n");

/**
 * The stylesheet for every palette. Light values are the default; dark applies
 * under `data-theme="dark"`, or under the OS dark scheme when no theme is set
 * (`data-theme` absent or "system"), and low-contrast dark on top of dark.
 */
export function paletteCss(): string {
  const out: string[] = [];
  // The OS scheme applies only when no theme is chosen (data-theme absent or "light"/"dark" wins).
  const system = (sel: string, body: string) => `@media (prefers-color-scheme: dark) {\n  ${sel} {\n${body}\n  }\n}`;
  const indent = (s: string) => s.split("\n").map((l) => (l ? `  ${l}` : l)).join("\n");
  out.push(`/* Generated from src/theme/palettes.ts. Do not edit by hand. */`);
  out.push(`:root, :root[data-color-palette="neutral"] {\n${block(PALETTES.neutral.light)}\n}`);
  out.push(`:root {\n${block(FIXED_TOKENS.light)}\n}`);
  for (const id of PALETTE_IDS) {
    const p = PALETTES[id];
    const sel = `:root[data-color-palette="${id}"]`;
    out.push(`${sel} {\n${block(p.light)}\n}`);
    out.push(`${sel}[data-theme="dark"] {\n${block(p.dark)}\n}`);
    out.push(system(`${sel}:not([data-theme="light"])`, indent(block(p.dark))));
  }
  out.push(`:root[data-theme="dark"] {\n${block(FIXED_TOKENS.dark)}\n}`);
  out.push(system(`:root:not([data-theme="light"])`, indent(block(FIXED_TOKENS.dark))));
  for (const id of PALETTE_IDS) {
    const sel = `:root[data-color-palette="${id}"][data-low-contrast]`;
    out.push(`${sel}[data-theme="dark"] {\n${block(PALETTES[id].lowContrast)}\n}`);
    out.push(system(`${sel}:not([data-theme="light"])`, indent(block(PALETTES[id].lowContrast))));
  }
  return out.join("\n\n") + "\n";
}

const STYLE_ID = "oc-palettes";

/** Adds the palette stylesheet to the document once; safe to call repeatedly. */
export function installPaletteStyles(doc: Document = document): void {
  if (doc.getElementById(STYLE_ID)) return;
  const style = doc.createElement("style");
  style.id = STYLE_ID;
  style.textContent = paletteCss();
  doc.head.appendChild(style);
}

/** Sets the palette on the document root; styles.css and tokens.css do the rest. */
export function applyPalette(id: PaletteId, root: HTMLElement = document.documentElement): void {
  root.dataset.colorPalette = id;
}
